    console.log('   • Backend API: backend/docs/API-GUIDE.md');
    console.log('   • Frontend Guide: frontend/README.md');
    console.log('   • Postman Collection: backend/GRIFFION_API.postman_collection.json\n');
    
    console.log('=' .repeat(60));
